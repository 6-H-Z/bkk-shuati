/* 从池中随机取 n 个互不相同的字符串，排除 exclude */
function gtvPickN(pool, n, exclude) {
  var arr = DZ_V.shuffle(pool), out = [], i, s;
  for (i = 0; i < arr.length && out.length < n; i++) {
    s = String(arr[i]);
    if (exclude !== undefined && s === String(exclude)) continue;
    if (out.indexOf(s) >= 0) continue;
    out.push(s);
  }
  return out;
}

/* 生成 3 个互不相同、且都不等于正确答案的干扰项 */
function gtvWrongs(correct, pool) {
  var out = gtvPickN(pool, 3, correct), fb = ["条件不足，无法判断", "题中未涉及的结论", "与题干无关的做法"], i;
  for (i = 0; i < fb.length && out.length < 3; i++) {
    if (fb[i] !== String(correct) && out.indexOf(fb[i]) < 0) out.push(fb[i]);
  }
  return out;
}

/* 统一组装，保证返回值就是 DZ_V.mk 的结果 */
function gtvMk(topic, stem, correct, wrongs, explain, level) {
  return DZ_V.mk({ topic: topic, stem: stem, correct: correct, wrongs: wrongs, explain: explain, level: level });
}

/* 按难度挑案例：案例用 lvs 数组标记支持哪些难度档 */
function gtvCasesByLevel(cases, level) {
  var out = [], i;
  for (i = 0; i < cases.length; i++) {
    if (!cases[i].lvs || cases[i].lvs.indexOf(level) >= 0) out.push(cases[i]);
  }
  return out;
}

