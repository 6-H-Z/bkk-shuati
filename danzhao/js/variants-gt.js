function gtvOrderWrongs(correct, n) {
  var c = correct.split(""), cands = [], i, t, tmp, out = [];
  for (i = 0; i + 1 < n; i++) {
    t = c.slice();
    tmp = t[i]; t[i] = t[i + 1]; t[i + 1] = tmp;
    cands.push(t.join(""));
  }
  cands.push(c.slice().reverse().join(""));
  cands.push(c.slice(1).concat([c[0]]).join(""));
  cands.push(c.slice(n - 1).concat(c.slice(0, n - 1)).join(""));
  cands = DZ_V.shuffle(cands);
  for (i = 0; i < cands.length && out.length < 3; i++) {
    if (cands[i] === correct || out.indexOf(cands[i]) >= 0) continue;
    out.push(cands[i]);
  }
  return out;
}

